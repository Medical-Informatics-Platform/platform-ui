/** Escapes a value for safe interpolation into strings bound with [innerHTML] or returned by an
 *  ECharts tooltip formatter (also HTML). */
export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
